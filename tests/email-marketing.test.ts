    assert.ok(reminder); assert.equal(await allowed("cart_reminder",reminder),true);
    assert.equal((await db.query("select * from email_outbox where event_type='cart_reminder'")).rows.length,1);
    await db.query("select save_email_cart_v1($1::jsonb)", [JSON.stringify([{ id: product, quantity: 3 }])]);
    assert.equal(await allowed("cart_reminder",reminder),false);
    await db.exec("update email_saved_carts set updated_at=now()-interval '25 hours'; select prepare_email_automations_v1();");
    assert.equal((await db.query("select * from email_outbox where event_type='cart_reminder'")).rows.length,1, "frequency cap remains across cart revisions");
    const campaign = randomUUID();
    await db.query("insert into email_campaigns(id,subject,heading,message) values($1,'Oferta','Novedades','Mensaje de prueba suficientemente largo')", [campaign]);
    await assert.rejects(db.query("select launch_email_campaign_v1($1)",[campaign]));
    await db.exec("select set_config('test.admin','true',false)");
    await db.query("select launch_email_campaign_v1($1)",[campaign]);
    await db.query("select launch_email_campaign_v1($1)",[campaign]);
    await db.exec("select prepare_email_automations_v1(); select prepare_email_automations_v1();");
    assert.equal((await db.query("select * from email_outbox where event_type='campaign'")).rows.length,1);
    const promotion = await snapshot("campaign");
    assert.equal(await allowed("campaign",promotion),true);
    await db.query("update email_campaigns set status='cancelled' where id=$1",[campaign]);
    assert.equal(await allowed("campaign",promotion),false);
    await db.query("update email_campaigns set status='queued_all' where id=$1",[campaign]);
    await db.query("update auth.users set email='changed@example.com' where id=$1",[first]);
    assert.equal(await allowed("campaign",promotion),false);
    await db.query("update auth.users set email='one@example.com' where id=$1",[first]);
    const token = (await db.query<{ unsubscribe_token:string }>("select unsubscribe_token from email_preferences where profile_id=$1",[first])).rows[0].unsubscribe_token;
