import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { PGlite } from "@electric-sql/pglite";

test("supplier intelligence: registry reuse, RLS, transactional history, stale evidence, errors and inventory isolation", async () => {
  const db=new PGlite();
  try {
    await db.exec(`create role anon; create role authenticated; create role service_role bypassrls; create schema auth;
      create function auth.uid() returns uuid language sql as $$ select '11111111-1111-4111-8111-111111111111'::uuid $$;
      create function public.is_admin() returns boolean language sql as $$ select coalesce(current_setting('test.admin',true),'false')='true' $$;
      create table public.suppliers(id uuid primary key default gen_random_uuid(),name text,website text,is_active boolean default true,notes text,created_at timestamptz default now());
      create table public.products(id uuid primary key,stock int,retail_price numeric);
      create table public.product_variants(id uuid primary key,product_id uuid references products(id));
      grant select,insert,update on suppliers to authenticated; grant usage on schema auth to authenticated;
      insert into suppliers(name,website,notes) values('Contacto existente','https://www.starcompany-py.com/','Conservar contacto');`);
    await db.exec(readFileSync("supabase/migrations/20261020120000_supplier_intelligence.sql","utf8"));
    assert.equal((await db.query<{n:number}>("select count(*)::int n from suppliers")).rows[0].n,9);
    assert.equal((await db.query<{notes:string}>("select notes from suppliers where official_key='star-company'")).rows[0].notes,"Conservar contacto");
    assert.equal((await db.query<{n:number}>("select count(*)::int n from suppliers where automation_authorized")).rows[0].n,0);
    const sid=(await db.query<{id:string}>("select id from suppliers where official_key='star-company'")).rows[0].id;
    await db.exec("insert into products values('22222222-2222-4222-8222-222222222222',7,99999)");
    const payload={supplier_id:sid,product_id:"22222222-2222-4222-8222-222222222222",external_id:"123",variant_key:"50ml",title:"Producto",source_url:"https://www.starcompany-py.com/p",origin_cost:10,currency:"USD",availability:"in_stock",verification:"verified",observed_at:new Date().toISOString(),method:"manual"};
    await db.exec("set role anon");
    for(const table of ["supplier_offers","supplier_observations","supplier_proposals","supplier_config_history","import_cost_policies","import_simulations","import_purchases"]) await assert.rejects(db.query(`select * from ${table}`),/permission denied/);
    await assert.rejects(db.query("select record_supplier_observation_v1($1)",[payload]),/permission denied/);
    await db.exec("reset role; set role authenticated; select set_config('test.admin','false',false)");
    assert.equal((await db.query("select * from import_cost_policies")).rows.length,0);
    await assert.rejects(db.query("select record_supplier_observation_v1($1)",[payload]),/Forbidden/);
    await assert.rejects(db.query("insert into import_cost_policies(config) values('{}')"),/row-level security/);
    await assert.rejects(db.query("insert into import_purchases(simulation_id,notes) values(gen_random_uuid(),'no')"),/row-level security/);
    await db.exec("select set_config('test.admin','true',false)");
    const record=async(p:unknown)=>(await db.query<{id:string}>("select record_supplier_observation_v1($1) id",[p])).rows[0].id;
    const oid=await record(payload);
    await assert.rejects(db.query("select claim_supplier_query_v1($1)",[oid]),/not authorized/);
    await db.query("update suppliers set automation_authorized=true where id=$1",[sid]);
    await db.query("select claim_supplier_query_v1($1)",[oid]);
    await assert.rejects(db.query("select claim_supplier_query_v1($1)",[oid]),/un minuto/);
    assert.equal((await db.query("select * from supplier_config_history")).rows.length,1);
    await record({...payload,title:"  Producto",origin_cost:12});
    assert.equal((await db.query("select * from supplier_offers")).rows.length,1);
    assert.equal((await db.query<{verification:string}>("select verification from supplier_offers")).rows[0].verification,"pending");
    await record({...payload,method:"error",message:"timeout"});
    const evidence=(await db.query<{origin_cost:string;availability:string;last_error:string}>("select origin_cost,availability,last_error from supplier_offers")).rows[0];
    assert.equal(evidence.origin_cost,"12"); assert.equal(evidence.availability,"in_stock"); assert.equal(evidence.last_error,"timeout");
    await record({...payload,method:"not_found",message:"404"});
    assert.equal((await db.query<{availability:string}>("select availability from supplier_offers")).rows[0].availability,"in_stock");
    await assert.rejects(record({...payload,observed_at:"2020-01-01T00:00:00Z"}),/older/);
    await assert.rejects(record({...payload,product_id:null}),/relinking/);
    await assert.rejects(record({...payload,variant_id:"33333333-3333-4333-8333-333333333333"}),/belong/);
    await record({...payload,availability:"out_of_stock"});
    assert.equal((await db.query<{availability:string}>("select availability from supplier_offers")).rows[0].availability,"out_of_stock");
    await record({...payload,origin_cost:null,currency:"PYG",availability:"unknown"});
    const retained=(await db.query<{origin_cost:string;currency:string}>("select origin_cost,currency from supplier_offers")).rows[0];
    assert.deepEqual(retained,{origin_cost:"10",currency:"USD"});
    const count=(await db.query<{n:number}>("select count(*)::int n from supplier_observations")).rows[0].n;
    await assert.rejects(db.query("select import_supplier_observations_v1($1)",[[{...payload,external_id:"second"},{...payload,external_id:"bad",origin_cost:-1}]]));
    assert.equal((await db.query<{n:number}>("select count(*)::int n from supplier_observations")).rows[0].n,count);
    assert.equal((await db.query("select * from supplier_offers")).rows.length,1);
    await assert.rejects(db.query("update supplier_observations set payload='{}'"),/permission denied/);
    await assert.rejects(db.query("delete from import_cost_policies"),/permission denied/);
    const proposals=(await db.query<{kind:string}>("select kind from supplier_proposals where offer_id=$1",[oid])).rows.map(p=>p.kind);
    for(const kind of ["new_candidate","cost","identity","missing_page","availability"]) assert.ok(proposals.includes(kind),kind);
    await db.exec("reset role");
    const physical=(await db.query<{stock:number;retail_price:string}>("select stock,retail_price from products")).rows[0];
    assert.deepEqual(physical,{stock:7,retail_price:"99999"});
    await db.exec("insert into product_variants values('33333333-3333-4333-8333-333333333333','22222222-2222-4222-8222-222222222222');set role authenticated");
    await assert.rejects(record({...payload,external_id:"variant-needed"}),/exact product variant/);
  } finally { await db.close(); }
});
